import fs from 'node:fs';
import path from 'node:path';
import vm from 'node:vm';
import { createHash } from 'node:crypto';

const root = process.cwd();
const catalogScripts = [
  'cases.js','curriculum.js','expanded-sources.js','additional-groups.js',
  'next-76-groups.js','next-200-groups.js','next-200-review.js','next-304-groups.js','expanded-cases.js'
];
const source = catalogScripts.map(file => fs.readFileSync(path.join(root,file),'utf8')).join('\n');
const payload = JSON.parse(vm.runInNewContext(source + '\nJSON.stringify({cases:CASES,curriculum:CURRICULUM})'));
const lessonById = new Map(payload.curriculum.map(lesson => [lesson.id,lesson]));
const contentVersion = '2026.09.2';

function sha256(value) {
  return createHash('sha256').update(value).digest('hex');
}

function canonical(value) {
  if (Array.isArray(value)) return '[' + value.map(canonical).join(',') + ']';
  if (value && typeof value === 'object') {
    return '{' + Object.keys(value).sort().map(key => JSON.stringify(key) + ':' + canonical(value[key])).join(',') + '}';
  }
  return JSON.stringify(value);
}

const records = payload.cases.map(item => {
  const id = path.basename(item.image,path.extname(item.image));
  const lesson = lessonById.get(id);
  if (!lesson) throw new Error(`Missing curriculum for ${id}`);
  const caseCore = {
    id,title:item.title,system:item.system,modality:item.modality,level:item.level,
    history:item.history,options:item.options,answer:item.answer,findings:item.findings,
    explain:item.explain,report:item.report,source:item.source,sourceUrl:item.sourceUrl,
    license:item.license,licenseUrl:item.licenseUrl || ''
  };
  const lessonCore = {
    id,english:lesson.english,recall:lesson.recall,methods:lesson.methods,tips:lesson.tips,
    pitfalls:lesson.pitfalls,differential:lesson.differential,pearl:lesson.pearl,
    limitation:lesson.limitation,refs:lesson.refs
  };
  const imageSha256 = sha256(fs.readFileSync(path.join(root,item.image)));
  const caseSha256 = sha256(canonical(caseCore));
  const lessonSha256 = sha256(canonical(lessonCore));
  const packageSha256 = sha256(canonical({schemaVersion:'1.0',contentVersion,id,caseSha256,lessonSha256,imageSha256}));
  return {
    id,schemaVersion:'1.0',contentVersion,caseSha256,lessonSha256,imageSha256,packageSha256,
    sourceVerified:Boolean(item.sourceEvidence)
  };
});

const output = `'use strict';\n\n// Generated by scripts/generate-case-packages.mjs. Do not edit by hand.\nconst CASE_PACKAGES = ${JSON.stringify(records)};\n`;
fs.writeFileSync(path.join(root,'case-packages.js'),output);
console.log(`Generated ${records.length} versioned case packages.`);
